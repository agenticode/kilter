// The integration tests below drive the real domain packages through the real
// CLI layer over RECORDED SNAPSHOTS in testdata/. Nothing here opens a socket,
// links an AWS SDK, or reads a clock: fixtureNow is the decision time
// everywhere, and every snapshot's timestamps are derived from it.
//
// The fixtures are generated by this file rather than hand-written JSON,
// because a hand-written 14-day 5-minute metric series is four thousand
// objects nobody will ever review. Regenerate with:
//
//	go test ./cmd/kilter -run TestWriteDomainFixtures -update-fixtures
//
// and commit the result. The generator is deterministic — same inputs, same
// bytes — so a regeneration that changes a file is a change in a domain
// package's collector, which is exactly when a reviewer should look.

var updateFixtures = flag.Bool("update-fixtures", false,
	"regenerate cmd/kilter/testdata domain snapshots")

// fixtureNow is the single decision time for every fixture and every test that
// reads one. It is a constant so a test can assert exact dollars.
var fixtureNow = time.Date(2026, 8, 26, 12, 0, 0, 0, time.UTC)

const (
	fixtureScope   = "000000000000/us-east-1"
	fixtureRegion  = "us-east-1"
	fixtureCluster = "prod"
)

func fixturePath(name string) string { return filepath.Join("testdata", name) }

// TestWriteDomainFixtures regenerates testdata/ when -update-fixtures is
// passed, and otherwise asserts that the committed fixtures still match what
// the generator produces. That second half is the point: it turns the
// fixtures into a contract test on the collectors that built them.
func TestWriteDomainFixtures(t *testing.T) {
	for _, f := range []struct {
		name  string
		build func(*testing.T) any
	}{
		{"ec2-instances.json", func(t *testing.T) any { return buildInstanceSnapshot(t) }},
		{"ec2-volumes.json", func(t *testing.T) any { return buildVolumeSnapshot(t) }},
		{"ecs-services.json", func(t *testing.T) any { return buildECSSnapshot(t) }},
		{"lambda-functions.json", func(t *testing.T) any { return buildLambdaSnapshot(t) }},
		{"commitments.json", func(t *testing.T) any { return buildInventory() }},
		{"cluster.json", func(t *testing.T) any { return buildClusterSnapshot() }},
	} {
		t.Run(f.name, func(t *testing.T) {
			want, err := json.Marshal(f.build(t))
			if err != nil {
				t.Fatalf("marshal: %v", err)
			}
			want = append(want, '\n')
			path := fixturePath(f.name)
			if *updateFixtures {
				if err := os.MkdirAll("testdata", 0o755); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(path, want, 0o644); err != nil {
					t.Fatal(err)
				}
				return
			}
			got, err := os.ReadFile(path)
			if err != nil {
				t.Fatalf("%v (run with -update-fixtures to create it)", err)
			}
			if string(got) != string(want) {
				t.Errorf("%s is stale: the generator no longer reproduces it.\n"+
					"Regenerate with -update-fixtures and review the diff — a change here "+
					"means a domain package's collector changed.", path)
			}
		})
	}
}

// buildInstanceSnapshot records a four-instance EC2 account through pkg/ec2's
// real collector, and wraps the result in the generic envelope's Payload.
//
// The four instances are chosen so the report exercises every arm of the
// engine at once:
//
//	i-…a  m5.2xlarge, over-provisioned, WITH a memory signal   → a real proposal
//	i-…b  r5.xlarge,  over-provisioned, NO memory signal       → memory-blind refusal
//	i-…c  t3.large,   idle but credit-depleted                 → burst refusal
//	i-…d  c5.large,   tagged as a Kubernetes node              → k8s-tagged refusal
//
// i-…a is the ONLY m5 in the account, which is what makes the commitment
// fixture bite: a size-flexible m5 reservation with a second m5 to land on
// would simply move its discount there, and the saving would be real.
func buildInstanceSnapshot(t *testing.T) *domain.Snapshot {
	t.Helper()
	const period = 5 * time.Minute
	const points = 2304 // 8 days of 5-minute datapoints

	fix := &kec2.Fixture{
		InventoryPages: []kec2.DescribeInstancesOutput{{
			Reservations: []kec2.Reservation{{
				ReservationID: "r-fixture",
				Instances: []kec2.InstanceRecord{
					{
						InstanceID: "i-0000000000000000a", InstanceType: "m5.2xlarge",
						Architecture: "x86_64", Tenancy: "default", State: "running",
						AvailabilityZone: fixtureRegion + "a", MonitoringState: "disabled",
						LaunchTime: fixtureNow.Add(-90 * 24 * time.Hour),
						Tags:       []kec2.Tag{{Key: "Name", Value: "report-renderer"}},
					},
					{
						InstanceID: "i-0000000000000000b", InstanceType: "r5.xlarge",
						Architecture: "x86_64", Tenancy: "default", State: "running",
						AvailabilityZone: fixtureRegion + "a", MonitoringState: "disabled",
						LaunchTime: fixtureNow.Add(-90 * 24 * time.Hour),
						Tags:       []kec2.Tag{{Key: "Name", Value: "search-indexer"}},
					},
					{
						InstanceID: "i-0000000000000000c", InstanceType: "t3.large",
						Architecture: "x86_64", Tenancy: "default", State: "running",
						AvailabilityZone: fixtureRegion + "b", MonitoringState: "disabled",
						CPUCredits: kec2.CreditModeStandard,
						LaunchTime: fixtureNow.Add(-90 * 24 * time.Hour),
						Tags:       []kec2.Tag{{Key: "Name", Value: "cron-runner"}},
					},
					{
						InstanceID: "i-0000000000000000d", InstanceType: "c5.large",
						Architecture: "x86_64", Tenancy: "default", State: "running",
						AvailabilityZone: fixtureRegion + "b", MonitoringState: "disabled",
						LaunchTime: fixtureNow.Add(-90 * 24 * time.Hour),
						Tags: []kec2.Tag{
							{Key: "Name", Value: "eks-node"},
							{Key: "kubernetes.io/cluster/prod", Value: "owned"},
						},
					},
				},
			}},
		}},
		Metrics: []kec2.RecordedSeries{
			// a: ~8 % CPU, ~18 % memory. Both signals present, so the sizer
			// may propose a smaller shape in BOTH dimensions.
			kec2.SyntheticSeries("i-0000000000000000a", kec2.MetricCPUUtilization,
				fixtureNow, period, points, []float64{7, 8, 9, 8}),
			kec2.SyntheticSeries("i-0000000000000000a", kec2.MetricMemUsedPercent,
				fixtureNow, period, points, []float64{17, 18, 19, 18}),
			// b: same idleness, no memory series at all — CloudWatch's default
			// for an instance with no agent. The memory floor becomes the
			// instance's current memory (§7 trap 4).
			kec2.SyntheticSeries("i-0000000000000000b", kec2.MetricCPUUtilization,
				fixtureNow, period, points, []float64{6, 7, 8, 7}),
			// c: idle-looking, but the credit balance is on the floor. The low
			// CPU is a ceiling AWS imposed, not demand (§7 trap 5).
			kec2.SyntheticSeries("i-0000000000000000c", kec2.MetricCPUUtilization,
				fixtureNow, period, points, []float64{29, 30, 31, 30}),
			kec2.SyntheticSeries("i-0000000000000000c", kec2.MetricCPUCreditBalance,
				fixtureNow, period, points, []float64{0, 0, 1, 0}),
			// d: a cluster node. Sized by the k8s-nodes pipeline, never here.
			kec2.SyntheticSeries("i-0000000000000000d", kec2.MetricCPUUtilization,
				fixtureNow, period, points, []float64{40, 45, 50, 45}),
		},
	}

	col, err := kec2.NewCollector(fix, fix, kec2.CollectorConfig{
		Scope: fixtureScope, Region: fixtureRegion,
		Window: 8 * 24 * time.Hour, CollectMemory: true,
	})
	if err != nil {
		t.Fatalf("ec2 collector: %v", err)
	}
	snap, err := col.Collect(context.Background(), fixtureNow)
	if err != nil {
		t.Fatalf("ec2 collect: %v", err)
	}
	return wrapPayload(t, domain.EC2, fixtureScope, snap)
}

// buildVolumeSnapshot records a three-volume EBS account through pkg/ebs's
// real collector. The generic envelope carries these as Targets and Samples —
// no Payload — because that is what pkg/ebs's own collector emits, and the
// integration test is worth more if it exercises the shipped path.
//
//	vol-…1  200 GiB gp2, lightly used   → gp2→gp3 conversion
//	vol-…2  350 GiB gp2                 → the 334-375 GiB parity REFUSAL band
//	vol-…3  100 GiB gp3                 → not-gp2 refusal
func buildVolumeSnapshot(t *testing.T) *domain.Snapshot {
	t.Helper()
	// 15-minute spacing over the 7-day window. Coverage is deliberately below
	// Config.MinCoverage, which is the interesting case: the proposal is then
	// FLOORED at gp2's delivered baseline rather than sized to measured
	// demand, so a thin observation can only ever produce a same-or-better
	// volume (pkg/ebs/FINDINGS.md §2, the floor rule).
	const period = 15 * time.Minute
	const points = 672

	vols := []kebs.VolumeRecord{
		{
			VolumeID: "vol-00000000000000001", VolumeType: kebs.VolumeTypeGP2,
			SizeGiB: 200, IOPS: 600, State: kebs.VolumeStateInUse,
			AvailabilityZone: fixtureRegion + "a",
			CreateTime:       fixtureNow.Add(-200 * 24 * time.Hour),
			Attachments: []kebs.VolumeAttachment{{
				InstanceID: "i-0000000000000000a", State: kebs.AttachmentAttached,
			}},
			Tags: []kebs.Tag{{Key: "Name", Value: "reports-data"}},
		},
		{
			VolumeID: "vol-00000000000000002", VolumeType: kebs.VolumeTypeGP2,
			SizeGiB: 350, IOPS: 1050, State: kebs.VolumeStateInUse,
			AvailabilityZone: fixtureRegion + "a",
			CreateTime:       fixtureNow.Add(-200 * 24 * time.Hour),
			Attachments: []kebs.VolumeAttachment{{
				InstanceID: "i-0000000000000000b", State: kebs.AttachmentAttached,
			}},
			Tags: []kebs.Tag{{Key: "Name", Value: "index-scratch"}},
		},
		{
			VolumeID: "vol-00000000000000003", VolumeType: kebs.VolumeTypeGP3,
			SizeGiB: 100, IOPS: 3000, ThroughputMBps: 125, State: kebs.VolumeStateInUse,
			AvailabilityZone: fixtureRegion + "b",
			CreateTime:       fixtureNow.Add(-30 * 24 * time.Hour),
			Tags:             []kebs.Tag{{Key: "Name", Value: "already-gp3"}},
		},
	}

	fix := &kebs.Fixture{
		InventoryPages: []kebs.DescribeVolumesOutput{{Volumes: vols}},
		Now:            func() time.Time { return fixtureNow },
	}
	// CloudWatch reports EBS ops as a Sum over the period, so the values below
	// are per-5-minute counts: 300 s × the IOPS we want to look like.
	for _, id := range []string{"vol-00000000000000001", "vol-00000000000000002"} {
		fix.Metrics = append(fix.Metrics,
			ebsSeries(id, kebs.MetricVolumeReadOps, period, points, 300*20),
			ebsSeries(id, kebs.MetricVolumeWriteOps, period, points, 300*25),
			ebsSeries(id, kebs.MetricVolumeReadBytes, period, points, 300*2*kebs.MiB),
			ebsSeries(id, kebs.MetricVolumeWriteBytes, period, points, 300*3*kebs.MiB),
		)
	}

	col, err := kebs.NewCollector(fix, fix, kebs.CollectorConfig{
		Scope: fixtureScope, Region: fixtureRegion, Window: 7 * 24 * time.Hour,
	})
	if err != nil {
		t.Fatalf("ebs collector: %v", err)
	}
	snap, err := col.Collect(context.Background(), fixtureNow)
	if err != nil {
		t.Fatalf("ebs collect: %v", err)
	}
	return snap
}

func ebsSeries(volumeID, metric string, period time.Duration, n int, value float64) kebs.RecordedSeries {
	pts := make([]kebs.Point, n)
	start := fixtureNow.Add(-time.Duration(n) * period)
	for i := range pts {
		pts[i] = kebs.Point{At: start.Add(time.Duration(i+1) * period), Value: value}
	}
	return kebs.RecordedSeries{VolumeID: volumeID, Metric: metric, Points: pts}
}

