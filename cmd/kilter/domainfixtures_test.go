func ecsSeries(metric string, period time.Duration, n int, values []float64) kecs.Series {
	s := kecs.Series{
		Metric: metric, PeriodSeconds: int32(period / time.Second),
		StatusCode: kecs.StatusComplete,
	}
	start := fixtureNow.Add(-time.Duration(n) * period)
	for i := 0; i < n; i++ {
		s.Timestamps = append(s.Timestamps, start.Add(time.Duration(i+1)*period))
		s.Values = append(s.Values, values[i%len(values)])
	}
	return s
}

// buildLambdaSnapshot records two Lambda functions.
//
//	tuned     measured at TWO memory settings → a claimable, measured saving
//	untuned   measured at one setting only    → the single-memory-point refusal
//
// The second is the fleet-wide default in reality, and the honest output for
// it is a refusal plus a power-tuning trial, not an estimate.
func buildLambdaSnapshot(t *testing.T) *domain.Snapshot {
	t.Helper()
	win := klambda.Window{Start: fixtureNow.Add(-14 * 24 * time.Hour), End: fixtureNow}
	// The Invocations metric is sized to match the REPORT lines that survived
	// parsing, because their ratio IS the report-coverage confidence factor: a
	// fixture with two thousand invocations and two hundred log lines would
	// fail on evidence coverage rather than on the arithmetic under test.

	tuned := klambda.Target{
		Ref: domain.TargetRef{
			Domain: domain.Lambda, Scope: fixtureScope,
			ID:   "arn:aws:lambda:us-east-1:000000000000:function:thumbnailer",
			Name: "thumbnailer",
		},
		Function: klambda.Function{
			ARN:          "arn:aws:lambda:us-east-1:000000000000:function:thumbnailer",
			Name:         "thumbnailer",
			MemoryMB:     1024,
			Architecture: klambda.ArchX86,
			PackageType:  klambda.PackageZip,
			Runtime:      "python3.12",
		},
	}
	// 1024 MB is what it runs on today, measured; 512 MB is a setting it ran
	// on earlier in the window (a retune, a rollback, a deliberate trial).
	// The duration at 512 MB is only ~1.6× longer, so half the memory is a
	// real, MEASURED reduction in GB-seconds.
	tuned.Reports = append(tuned.Reports,
		parseSynthetic(t, "thumb-hi", fixtureNow.Add(-7*24*time.Hour), 7*24*time.Hour,
			600, 42.0, 1024, 300)...)
	tuned.Reports = append(tuned.Reports,
		parseSynthetic(t, "thumb-lo", fixtureNow.Add(-14*24*time.Hour), 7*24*time.Hour,
			600, 68.0, 512, 300)...)
	tuned.Series = append(tuned.Series, klambda.Series{
		Metric: klambda.MetricInvocations,
		Points: klambda.SyntheticMetric(win.Start, time.Hour, 336, 4.0),
	})

	untuned := klambda.Target{
		Ref: domain.TargetRef{
			Domain: domain.Lambda, Scope: fixtureScope,
			ID:   "arn:aws:lambda:us-east-1:000000000000:function:webhook",
			Name: "webhook",
		},
		Function: klambda.Function{
			ARN:          "arn:aws:lambda:us-east-1:000000000000:function:webhook",
			Name:         "webhook",
			MemoryMB:     512,
			Architecture: klambda.ArchX86,
			PackageType:  klambda.PackageZip,
			Runtime:      "nodejs20.x",
		},
	}
	untuned.Reports = parseSynthetic(t, "hook", win.Start, 14*24*time.Hour,
		1100, 25.0, 512, 74)
	untuned.Series = append(untuned.Series, klambda.Series{
		Metric: klambda.MetricInvocations,
		Points: klambda.SyntheticMetric(win.Start, time.Hour, 336, 3.5),
	})

	native := &klambda.Snapshot{
		Domain: domain.Lambda, Scope: fixtureScope, Region: fixtureRegion,
		Timestamp: fixtureNow, Window: win,
		Targets: []klambda.Target{tuned, untuned},
	}
	klambda.SortTargets(native.Targets)
	return wrapPayload(t, domain.Lambda, fixtureScope, native)
}

// parseSynthetic builds REPORT log lines and parses them back, so the fixture
// carries records that went through the real parser rather than structs a test
// filled in by hand.
func parseSynthetic(t *testing.T, prefix string, start time.Time, span time.Duration,
	n int, billedMS float64, memoryMB, maxUsedMB int64) []klambda.ReportRecord {
	t.Helper()
	// coldEvery = 0 ⇒ every invocation is warm. Cold records never contribute
	// to warm duration statistics, and a fixture that mixed the two at
	// different memory settings would invent a cost difference memory had
	// nothing to do with.
	events := klambda.SyntheticReports(prefix, start, span, n, memoryMB, maxUsedMB, billedMS, 0, 0)
	recs, drops := klambda.ParseEvents(events)
	if len(drops) > 0 {
		t.Fatalf("synthetic REPORT lines were dropped: %v", drops)
	}
	if len(recs) != n {
		t.Fatalf("parsed %d records, want %d", len(recs), n)
	}
	return recs
}

// buildInventory is the commitment position that makes §7 trap 1 concrete: a
// standard m5.2xlarge Reserved Instance covering exactly the instance the EC2
// sizer wants to shrink.
//
// The RI bills whether or not usage absorbs it. Downsizing that instance to
// m5.large leaves most of the reservation stranded, so the *bill* barely moves
// — or moves the wrong way — while the list-price delta looks like $210/month.
// That is the number a naive optimizer reports and this one refuses to.
func buildInventory() *kcommit.Inventory {
	return &kcommit.Inventory{
		FetchedAt: fixtureNow.Add(-24 * time.Hour),
		RIs: []kcommit.ReservedInstance{{
			ID: "ri-fixture-m5", Count: 1, InstanceType: "m5.2xlarge",
			Region: fixtureRegion, Platform: kcommit.PlatformLinux,
			OfferingClass: "standard", EffectiveHourlyUSD: 0.242,
			Expires: fixtureNow.Add(300 * 24 * time.Hour),
		}},
	}
}

// buildClusterSnapshot is a minimal EKS-on-Fargate cluster: one Fargate pod
// sitting exactly on the §4.1.1 overhead cliff. It requests 1 vCPU / 8 GiB and
// AWS bills it 2 vCPU / 9 GB, because Fargate adds 256 MiB of Kubernetes
// overhead before rounding up to a tier — so 8 GiB of request costs a whole
// extra vCPU.
//
// It is the model.ClusterSnapshot format `kilter analyze --dump-snapshot` and
// `kilter simulate` already use, so this fixture doubles as a check that the
// k8s-fargate domain reads the collector's real output.
func buildClusterSnapshot() *model.ClusterSnapshot {
	ref := model.WorkloadRef{Kind: model.KindDeployment, Namespace: "default", Name: "api"}
	snap := &model.ClusterSnapshot{
		ClusterID: "prod-eks",
		Timestamp: fixtureNow,
		Nodes: []model.NodeSpec{{
			Name:      "fargate-ip-10-0-1-5.ec2.internal",
			Labels:    map[string]string{model.LabelComputeType: "fargate"},
			ManagedBy: model.ManagedByFargate,
			// A Fargate VM reports an absurd shell capacity. §7 trap 7: fed to
			// binpack it produces nonsense; pricing.SplitFargate is what keeps
			// it out, and this fixture is the reason to prove it.
			Capacity:    model.Resources{MilliCPU: 96000, MemoryBytes: 384 << 30},
			Allocatable: model.Resources{MilliCPU: 96000, MemoryBytes: 384 << 30},
			Ready:       true,
			Provider:    "aws", Region: fixtureRegion, Zone: fixtureRegion + "a",
		}},
		Pods: []model.PodSpec{{
			UID: "pod-fargate-1", Name: "api-0", Namespace: "default",
			Workload: ref, NodeName: "fargate-ip-10-0-1-5.ec2.internal",
			Phase:     "Running",
			CreatedAt: fixtureNow.Add(-30 * 24 * time.Hour),
			Containers: []model.ContainerSpec{{
				Name:     "api",
				Requests: model.Resources{MilliCPU: 1000, MemoryBytes: 8 << 30},
			}},
			// The AWS-stamped billed capacity. It outranks any computed
			// estimate, and it is what the quantizer is validated against.
			ProvisionedCapacity: model.Resources{MilliCPU: 2000, MemoryBytes: 9 * 1000 * 1000 * 1000},
		}},
		Workloads: []model.WorkloadInfo{{Ref: ref, Replicas: 1, Ready: 1}},
	}
	// Three days of one-minute samples: a steady 300 mCPU and a 7 GiB memory
	// peak, comfortably under the 8 GiB request. That is what makes the
	// boundary shave arithmetically interesting — dropping the request by
	// 256 MiB lands the pod a whole vCPU cheaper.
	key := model.ContainerKey{Workload: ref, Container: "api"}
	const samples = 288 // three days at 15-minute spacing
	const spacing = 15 * time.Minute
	start := fixtureNow.Add(-time.Duration(samples) * spacing)
	mem := []int64{6_900_000_000, 7_000_000_000, 6_950_000_000, 7_010_000_000}
	for i := 0; i < samples; i++ {
		snap.Usage = append(snap.Usage, model.Usage{
			Key: key, PodUID: "pod-fargate-1",
			Timestamp:     start.Add(time.Duration(i+1) * spacing),
			MilliCPU:      300,
			MemoryBytes:   mem[i%len(mem)],
			WindowSeconds: int32(spacing / time.Second),
		})
	}
	return snap
}

// wrapPayload puts a domain-native snapshot into the generic envelope's opaque
// Payload — the field pkg/lambda/FINDINGS.md §8 asked a later unit to add.
func wrapPayload(t *testing.T, k domain.Kind, scope string, native any) *domain.Snapshot {
	t.Helper()
	raw, err := json.Marshal(native)
	if err != nil {
		t.Fatalf("marshal %s payload: %v", k, err)
	}
	return &domain.Snapshot{
		Domain: k, Scope: scope, Timestamp: fixtureNow, Payload: raw,
	}
}

// readFixture is the test-side counterpart: it loads a committed fixture the
// same way the CLI does.
func readFixture(t *testing.T, name string) string {
	t.Helper()
	path := fixturePath(name)
	if _, err := os.Stat(path); err != nil {
		t.Skipf("fixture %s is missing: %v (run with -update-fixtures)", path, err)
	}
	return path
}

func mustJSON(t *testing.T, v any) string {
	t.Helper()
	b, err := json.Marshal(v)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

